def main():
    parser = argparse.ArgumentParser(description="Generate types across SDKs from JSON schema.")
    parser.add_argument("--check", action="store_true", help="Check that existing files match generated output without modifying.")
    args = parser.parse_args()

    targets = [
        (ROOT_DIR / "web" / "src" / "schema" / "models.ts", generate_typescript()),
        (ROOT_DIR / "server" / "src" / "models.ts", generate_typescript()),
        (ROOT_DIR / "core" / "src" / "commonMain" / "kotlin" / "dev" / "streampulse" / "core" / "schema" / "StreamPulseModels.kt", generate_kotlin()),
        (ROOT_DIR / "ios" / "Sources" / "StreamPulseSDK" / "Schema" / "StreamPulseModels.swift", generate_swift())
    ]

    mismatches = []
    for path, content in targets:
        if args.check:
            if not path.exists():
                mismatches.append(f"Missing file: {path}")
            else:
                existing = path.read_text(encoding="utf-8")
                if existing != content:
                    mismatches.append(f"Stale generated code: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Generated {path.relative_to(ROOT_DIR)}")

    if args.check:
        if mismatches:
            print("[FAIL] Generated code is not up to date:")
            for m in mismatches:
                print(f"       - {m}")
            sys.exit(1)
        else:
            print("[PASS] All generated files are fresh.")


if __name__ == "__main__":
    main()
